import React from 'react';
import {AbsoluteFill, Audio, Img, staticFile, useCurrentFrame} from 'remotion';
import {Runner} from './puppet/Runner';
import {celPath, exactCelIndex} from './cels';

/**
 * Labelled 4-panel comparison, all panels driven by the SAME timeline frame:
 *   top-left     SOURCE            original extracted frame (960x540 PNG)
 *   top-right    EXACT 94 CELS     cel94/f_{frame+1}.svg scaled 0.5
 *   bottom-left  PUPPET            procedural Runner scaled 0.5
 *   bottom-right 50% OVERLAY       source with the exact cel at 50% opacity
 *
 * Labels are HTML rendered by Remotion — NOT ffmpeg drawtext (the bundled
 * static ffmpeg has no drawtext filter). Source frames come from
 * public/srcframes/ (960x540, regenerated by tools/extract-frames.js), so the
 * reference panel is never resampled. The source panel is a still <Img>, not
 * a <Video>, so no extra audio is introduced; the original audio is attached
 * exactly once at this composition root.
 */

const PANEL_W = 960;
const PANEL_H = 540;

const Label: React.FC<{text: string}> = ({text}) => (
  <div
    style={{
      position: 'absolute',
      top: 0,
      left: 0,
      background: 'rgba(48,48,58,0.88)',
      color: '#FFFFFF',
      fontFamily: 'DejaVu Sans, Arial, sans-serif',
      fontSize: 26,
      fontWeight: 700,
      padding: '8px 18px',
      letterSpacing: 1,
      zIndex: 10,
    }}
  >
    {text}
  </div>
);

const Panel: React.FC<{x: number; y: number; label: string; children: React.ReactNode}> = ({
  x,
  y,
  label,
  children,
}) => (
  <div
    style={{
      position: 'absolute',
      left: x,
      top: y,
      width: PANEL_W,
      height: PANEL_H,
      overflow: 'hidden',
      background: '#fff',
      boxSizing: 'border-box',
      border: '2px solid #30303A',
    }}
  >
    {children}
    <Label text={label} />
  </div>
);

/** Scale a 1920x1080 layer into a 960x540 panel without resampling the source. */
const HalfScale: React.FC<{children: React.ReactNode; opacity?: number}> = ({children, opacity = 1}) => (
  <div
    style={{
      width: 1920,
      height: 1080,
      transform: 'scale(0.5)',
      transformOrigin: 'top left',
      opacity,
      position: 'absolute',
      top: 0,
      left: 0,
    }}
  >
    {children}
  </div>
);

export const Comparison: React.FC = () => {
  const frame = useCurrentFrame();
  const src = staticFile(`srcframes/f_${String(frame + 1).padStart(3, '0')}.png`);
  const cel = staticFile(celPath('cel94', exactCelIndex(frame)));
  return (
    <AbsoluteFill style={{background: '#FFFFFF'}}>
      <Panel x={0} y={0} label={`SOURCE  f${frame + 1}`}>
        <Img src={src} style={{width: PANEL_W, height: PANEL_H}} />
      </Panel>
      <Panel x={PANEL_W} y={0} label={`EXACT 94 CELS  f${frame + 1}`}>
        <HalfScale>
          <Img src={cel} style={{width: 1920, height: 1080}} />
        </HalfScale>
      </Panel>
      <Panel x={0} y={PANEL_H} label={`PUPPET  f${frame + 1}`}>
        <HalfScale>
          <Runner frame={frame} />
        </HalfScale>
      </Panel>
      <Panel x={PANEL_W} y={PANEL_H} label={`50% OVERLAY  SOURCE + EXACT  f${frame + 1}`}>
        <Img src={src} style={{width: PANEL_W, height: PANEL_H}} />
        <HalfScale opacity={0.5}>
          <Img src={cel} style={{width: 1920, height: 1080}} />
        </HalfScale>
      </Panel>
      <Audio src={staticFile('audio.m4a')} />
    </AbsoluteFill>
  );
};
